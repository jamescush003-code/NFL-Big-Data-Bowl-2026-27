"""Step 2: get the competition data into data/raw/ and document its schema in data/SCHEMA.md."""
import shutil
import zipfile
from pathlib import Path

import pyarrow.csv as pv

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
COMPETITION = "nfl-big-data-bowl-2027"


def find_local_zip():
    # Chrome leaves finished-but-unrenamed downloads as .crdownload; accept any real zip in the folder.
    for f in sorted(ROOT.iterdir()):
        if f.is_file() and f.suffix in (".zip", ".crdownload") and zipfile.is_zipfile(f):
            return f
    return None


def extract(zip_path):
    RAW.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path) as z:
        for m in z.infolist():
            if m.is_dir():
                continue
            target = RAW / Path(m.filename).name  # flatten the archive's top folder
            with z.open(m) as src, open(target, "wb") as dst:
                shutil.copyfileobj(src, dst)


def get_data():
    if RAW.exists() and any(RAW.glob("*.csv")):
        print(f"data/raw already populated ({len(list(RAW.glob('*.csv')))} csv files)")
        return
    z = find_local_zip()
    if z:
        print(f"Extracting {z.name} -> data/raw/")
        extract(z)
        return
    import kagglehub

    path = Path(kagglehub.competition_download(COMPETITION))
    print("Path to competition files:", path)
    RAW.mkdir(parents=True, exist_ok=True)
    for f in path.rglob("*"):
        if f.suffix == ".zip":
            extract(f)
        elif f.is_file():
            shutil.copy2(f, RAW / f.name)


def describe(csv):
    """Stream the file once with pyarrow: row count + inferred schema, without loading it all."""
    reader = pv.open_csv(
        csv,
        read_options=pv.ReadOptions(block_size=64 << 20),
        convert_options=pv.ConvertOptions(null_values=["NA", ""], strings_can_be_null=True),
    )
    rows = sum(b.num_rows for b in reader)
    return rows, reader.schema


def write_schema():
    lines = ["# Raw data schema", "", f"Source: Kaggle competition `{COMPETITION}`. Generated by `src/01_load_data.py`.", ""]
    for csv in sorted(RAW.glob("*.csv")):
        rows, schema = describe(csv)
        print(f"{csv.name}: {rows:,} rows, {len(schema)} cols")
        lines += [f"## {csv.name}", "", f"- Rows: {rows:,}", f"- Size: {csv.stat().st_size / 1e6:,.1f} MB", "",
                  "| column | dtype |", "|---|---|"]
        lines += [f"| {f.name} | {f.type} |" for f in schema]
        lines.append("")
    (ROOT / "data" / "SCHEMA.md").write_text("\n".join(lines))
    print("Wrote data/SCHEMA.md")


if __name__ == "__main__":
    get_data()
    write_schema()
